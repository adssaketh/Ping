// Turns the lucide icons the old app imports (src/**/*.tsx) into Kotlin data, so the native app draws the SAME icons.
// lucide-react (ISC licence) must be available: `npm i --no-save lucide-react@0.546.0` (same version as package.json asks for)
// Run from the repo root:  LUCIDE_DIR=/path/to/node_modules/lucide-react node native/tools/icons/gen-icons.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const LUCIDE = process.env.LUCIDE_DIR || 'node_modules/lucide-react';
const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));
const names = new Set();
for (const f of walk('src').filter((f) => /\.tsx?$/.test(f))) {
  const t = readFileSync(f, 'utf8');
  for (const m of t.matchAll(/import\s*\{([^}]*)\}\s*from\s*'lucide-react'/g)) {
    m[1].split(',').map((s) => s.trim().replace(/\s+as\s+.*/, '')).filter(Boolean).forEach((n) => names.add(n));
  }
}
const kebab = (n) => n.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();
const num = (v) => String(+(+v).toFixed(4));
const toPath = (tag, a) => {
  switch (tag) {
    case 'path': return a.d;
    case 'circle': { const { cx, cy, r } = a; return `M${num(cx - r)} ${cy}a${r} ${r} 0 1 0 ${num(2 * r)} 0a${r} ${r} 0 1 0 ${num(-2 * r)} 0`; }
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': return 'M' + a.points.trim().split(/\s+/).join('L');
    case 'polygon': return 'M' + a.points.trim().split(/\s+/).join('L') + 'Z';
    case 'rect': {
      const x = +a.x || 0, y = +a.y || 0, w = +a.width, h = +a.height; let rx = +(a.rx ?? a.ry ?? 0), ry = +(a.ry ?? a.rx ?? 0);
      rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
      if (!rx && !ry) return `M${x} ${y}H${num(x + w)}V${num(y + h)}H${x}Z`;
      return `M${num(x + rx)} ${y}H${num(x + w - rx)}A${rx} ${ry} 0 0 1 ${num(x + w)} ${num(y + ry)}V${num(y + h - ry)}A${rx} ${ry} 0 0 1 ${num(x + w - rx)} ${num(y + h)}H${num(x + rx)}A${rx} ${ry} 0 0 1 ${x} ${num(y + h - ry)}V${num(y + ry)}A${rx} ${ry} 0 0 1 ${num(x + rx)} ${y}Z`;
    }
    case 'ellipse': { const { cx, cy, rx, ry } = a; return `M${num(cx - rx)} ${cy}a${rx} ${ry} 0 1 0 ${num(2 * rx)} 0a${rx} ${ry} 0 1 0 ${num(-2 * rx)} 0`; }
    default: throw new Error('unsupported tag ' + tag);
  }
};
let kt = `// GENERATED by native/tools/icons/gen-icons.mjs from lucide-react (ISC licence, https://lucide.dev). Do not edit by hand.\n@file:Suppress("ktlint")\npackage com.ping.sms.ui.icons\n\n/** Every lucide icon the old web app imports, as 24x24 stroke paths (2 px, round caps), same shapes as today. */\nobject Lucide {\n`;
const missing = [];
for (const n of [...names].sort()) {
  const file = join(LUCIDE, 'dist/esm/icons', kebab(n) + '.js');
  if (!existsSync(file)) { missing.push(n); continue; }
  let src = readFileSync(file, 'utf8');
  // some icons are renamed aliases that re-export another icon's file: follow them
  for (let hop = 0; hop < 4 && !src.includes('const __iconNode'); hop++) {
    const m = src.match(/from\s*['"]\.\/([a-z0-9-]+)\.js['"]/);
    if (!m) break;
    src = readFileSync(join(LUCIDE, 'dist/esm/icons', m[1] + '.js'), 'utf8');
  }
  const start = src.indexOf('const __iconNode =');
  if (start < 0) { missing.push(n); continue; }
  const end = src.indexOf('];', start) + 1;
  const arr = new Function('return ' + src.slice(start + 'const __iconNode ='.length, end))();
  const paths = arr.map(([tag, attrs]) => toPath(tag, attrs));
  kt += `  val ${n} = LucideIcon("${n}", listOf(\n${paths.map((p) => `    ${JSON.stringify(p)},`).join('\n')}\n  ))\n`;
}
kt += '}\n';
writeFileSync('native/app/src/main/java/com/ping/sms/ui/icons/LucideData.kt', kt, { flag: 'w' });
console.log('icons', names.size - missing.length, 'missing', missing.join(',') || 'none');
